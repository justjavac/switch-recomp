import fs from "node:fs/promises";
import { execFile } from "node:child_process";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);
const projectsPath = new URL("../src/lib/projects.ts", import.meta.url);
const sitePath = new URL("../src/lib/site.ts", import.meta.url);
const updatesPath = new URL("../src/lib/project-updates.ts", import.meta.url);

const source = await fs.readFile(projectsPath, "utf8");
const entries = Array.from(
  source.matchAll(
    /repo: "([^"]+)",\n\s+host: "(github|gitlab)",\n\s+stars: (\d+),/g,
  ),
  (match) => ({ repo: match[1], host: match[2], stars: Number(match[3]) }),
);

if (entries.length === 0) {
  throw new Error("No repositories found in projects.ts");
}

async function requestJson(url, headers = {}) {
  const args = [
    "-sS",
    "--fail-with-body",
    "--max-time",
    "20",
    "-A",
    "switchrecomp-star-sync",
  ];

  for (const [key, value] of Object.entries(headers)) {
    args.push("-H", `${key}: ${value}`);
  }

  args.push(url);

  const { stdout } = await execFileAsync("curl", args, {
    maxBuffer: 1024 * 1024,
  });

  return JSON.parse(stdout);
}

function normalizeDate(value) {
  return typeof value === "string" && value.length >= 10
    ? value.slice(0, 10)
    : undefined;
}

async function fetchGithubRepo(repo) {
  try {
    const { stdout } = await execFileAsync(
      "gh",
      [
        "api",
        `repos/${repo}`,
        "--jq",
        "[.stargazers_count, .pushed_at] | @tsv",
      ],
      { maxBuffer: 1024 * 1024 },
    );
    const [stars, pushedAt] = stdout.trim().split("\t");
    return {
      stars: Number(stars),
      updatedAt: normalizeDate(pushedAt),
    };
  } catch {
    console.warn(`GitHub ${repo}: gh unavailable, retrying anonymously`);
  }

  try {
    const data = await requestJson(`https://api.github.com/repos/${repo}`, {
      Accept: "application/vnd.github+json",
    });
    return {
      stars: data.stargazers_count,
      updatedAt: normalizeDate(data.pushed_at),
    };
  } catch (error) {
    console.warn(`GitHub ${repo}: ${error.stderr ?? error.message}`);
    return null;
  }
}

async function fetchGitlabRepo(repo) {
  try {
    const data = await requestJson(
      `https://gitlab.com/api/v4/projects/${encodeURIComponent(repo)}`,
    );
    return {
      stars: data.star_count,
      updatedAt: normalizeDate(data.last_activity_at ?? data.updated_at),
    };
  } catch (error) {
    console.warn(`GitLab ${repo}: ${error.stderr ?? error.message}`);
    return null;
  }
}

const latest = new Map();

for (const entry of entries) {
  const result =
    entry.host === "gitlab"
      ? await fetchGitlabRepo(entry.repo)
      : await fetchGithubRepo(entry.repo);

  if (result) {
    latest.set(`${entry.host}:${entry.repo}`, result);
  }

  await new Promise((resolve) => setTimeout(resolve, 200));
}

let updated = 0;
const nextSource = source.replace(
  /(repo: "([^"]+)",\n\s+host: "(github|gitlab)",\n\s+stars: )(\d+)/g,
  (match, prefix, repo, host, current) => {
    const result = latest.get(`${host}:${repo}`);
    if (result === undefined || result.stars === Number(current)) {
      return match;
    }
    updated += 1;
    return `${prefix}${result.stars}`;
  },
);

await fs.writeFile(projectsPath, nextSource);

const today = new Intl.DateTimeFormat("en-CA", {
  timeZone: "Asia/Shanghai",
}).format(new Date());
const displayDate = today.replaceAll("-", ".");

const siteSource = await fs.readFile(sitePath, "utf8");
const nextSite = siteSource
  .replace(/updatedAt: "[^"]+"/, `updatedAt: "${today}"`)
  .replace(/snapshotDate: "[^"]+"/, `snapshotDate: "${displayDate}"`);

if (nextSite !== siteSource) {
  await fs.writeFile(sitePath, nextSite);
}

async function readExistingUpdates() {
  try {
    const text = await fs.readFile(updatesPath, "utf8");
    const match = text.match(/= (\{[\s\S]*\});/);
    return match ? JSON.parse(match[1]) : {};
  } catch {
    return {};
  }
}

const previousUpdates = await readExistingUpdates();
const updates = { ...previousUpdates };

for (const entry of entries) {
  const result = latest.get(`${entry.host}:${entry.repo}`);
  if (result?.updatedAt) {
    updates[entry.repo] = result.updatedAt;
  }
}

const sortedUpdates = Object.fromEntries(
  Object.entries(updates).sort(([a], [b]) => a.localeCompare(b)),
);
const updatesSource = `// Generated by scripts/sync-stars.mjs. Do not edit manually.\n// Last synced: ${today}\nexport const projectUpdates: Record<string, string> = ${JSON.stringify(sortedUpdates, null, 2)};\n`;
await fs.writeFile(updatesPath, updatesSource);

console.log(
  `Checked ${entries.length} repositories, updated ${updated} star counts, wrote ${Object.keys(sortedUpdates).length} update dates, snapshot ${displayDate}.`,
);
